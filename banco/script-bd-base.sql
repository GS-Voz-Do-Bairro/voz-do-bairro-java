-- Limpeza (ordem reversa das FKs)
BEGIN
  FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
    'VB_AUDITORIA_APOIO','VB_IDEMPOTENCIA','VB_NOTIFICACAO','VB_APOIO','VB_COMENTARIO',
    'VB_RESPOSTA','VB_PROPOSTA','VB_USUARIO','VB_BAIRRO')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

CREATE TABLE VB_BAIRRO (
  ID             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME           VARCHAR2(100) NOT NULL,
  SUBPREFEITURA  VARCHAR2(100) NOT NULL,
  CIDADE         VARCHAR2(100) DEFAULT 'São Paulo' NOT NULL,
  META_APOIOS_PADRAO NUMBER(6) DEFAULT 50 NOT NULL CHECK (META_APOIOS_PADRAO > 0),
  CONSTRAINT UK_VB_BAIRRO_NOME UNIQUE (NOME, CIDADE)
);

CREATE TABLE VB_USUARIO (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME         VARCHAR2(120) NOT NULL,
  EMAIL        VARCHAR2(150) NOT NULL,
  SENHA_HASH   VARCHAR2(100) NOT NULL,
  PAPEL        VARCHAR2(20)  DEFAULT 'CIDADAO' NOT NULL,
  BAIRRO_ID    NUMBER REFERENCES VB_BAIRRO(ID),
  DT_CADASTRO  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UK_VB_USUARIO_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_VB_USUARIO_PAPEL CHECK (PAPEL IN ('CIDADAO','GESTOR'))
);

CREATE TABLE VB_PROPOSTA (
  ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TITULO            VARCHAR2(150)  NOT NULL,
  DESCRICAO         VARCHAR2(2000) NOT NULL,
  CATEGORIA         VARCHAR2(30)   NOT NULL,
  STATUS            VARCHAR2(20)   DEFAULT 'ABERTA' NOT NULL,
  RESUMO_IA         VARCHAR2(1000),
  META_APOIOS       NUMBER(6)      DEFAULT 50 NOT NULL,
  TOTAL_APOIOS      NUMBER(6)      DEFAULT 0  NOT NULL,
  AUTOR_ID          NUMBER NOT NULL REFERENCES VB_USUARIO(ID),
  BAIRRO_ID         NUMBER NOT NULL REFERENCES VB_BAIRRO(ID),
  DT_CRIACAO        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DT_VIROU_DEMANDA  TIMESTAMP,
  PRAZO_RESPOSTA    TIMESTAMP,
  CONSTRAINT CK_VB_PROPOSTA_CATEGORIA CHECK (CATEGORIA IN
    ('ZELADORIA','MOBILIDADE','SAUDE','EDUCACAO','LAZER','SEGURANCA','MEIO_AMBIENTE','OUTROS')),
  CONSTRAINT CK_VB_PROPOSTA_STATUS CHECK (STATUS IN
    ('ABERTA','DEMANDA','ATRASADA','EM_EXECUCAO','CONCLUIDA','RECUSADA')),
  CONSTRAINT CK_VB_PROPOSTA_APOIOS CHECK (TOTAL_APOIOS >= 0 AND META_APOIOS > 0)
);

CREATE TABLE VB_RESPOSTA (
  ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROPOSTA_ID     NUMBER NOT NULL REFERENCES VB_PROPOSTA(ID) ON DELETE CASCADE,
  GESTOR_ID       NUMBER NOT NULL REFERENCES VB_USUARIO(ID),
  DECISAO         VARCHAR2(20)   NOT NULL,
  JUSTIFICATIVA   VARCHAR2(2000) NOT NULL,
  PRAZO_EXECUCAO  DATE,
  DT_RESPOSTA     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UK_VB_RESPOSTA_PROPOSTA UNIQUE (PROPOSTA_ID),
  CONSTRAINT CK_VB_RESPOSTA_DECISAO CHECK (DECISAO IN ('ACEITA','RECUSADA'))
);

CREATE TABLE VB_COMENTARIO (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROPOSTA_ID  NUMBER NOT NULL REFERENCES VB_PROPOSTA(ID) ON DELETE CASCADE,
  USUARIO_ID   NUMBER NOT NULL REFERENCES VB_USUARIO(ID),
  TEXTO        VARCHAR2(1000) NOT NULL,
  DT_CRIACAO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  DT_EDICAO    TIMESTAMP
);

CREATE TABLE VB_APOIO (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PROPOSTA_ID  NUMBER NOT NULL REFERENCES VB_PROPOSTA(ID) ON DELETE CASCADE,
  USUARIO_ID   NUMBER NOT NULL REFERENCES VB_USUARIO(ID),
  DT_APOIO     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UK_VB_APOIO UNIQUE (PROPOSTA_ID, USUARIO_ID)
);

CREATE TABLE VB_NOTIFICACAO (
  ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID   NUMBER NOT NULL REFERENCES VB_USUARIO(ID),
  PROPOSTA_ID  NUMBER REFERENCES VB_PROPOSTA(ID) ON DELETE CASCADE,
  MENSAGEM     VARCHAR2(500) NOT NULL,
  LIDA         NUMBER(1) DEFAULT 0 NOT NULL CHECK (LIDA IN (0,1)),
  DT_CRIACAO   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE VB_IDEMPOTENCIA (
  CHAVE            VARCHAR2(100) NOT NULL,
  USUARIO_ID       NUMBER NOT NULL,
  ENDPOINT         VARCHAR2(200) NOT NULL,
  HASH_REQUISICAO  VARCHAR2(64)  NOT NULL,
  STATUS_HTTP      NUMBER(3)     NOT NULL,
  CORPO_RESPOSTA   CLOB,
  DT_CRIACAO       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_VB_IDEMPOTENCIA PRIMARY KEY (CHAVE, USUARIO_ID)
);

CREATE TABLE VB_AUDITORIA_APOIO (
  ID               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  OPERACAO         VARCHAR2(10) NOT NULL,
  APOIO_ID         NUMBER,
  PROPOSTA_ID      NUMBER,
  USUARIO_ID       NUMBER,
  VALORES_ANTIGOS  VARCHAR2(4000),
  VALORES_NOVOS    VARCHAR2(4000),
  DT_OPERACAO      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  USUARIO_BD       VARCHAR2(100) DEFAULT USER NOT NULL
);

