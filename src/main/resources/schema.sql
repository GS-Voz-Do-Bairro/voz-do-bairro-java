-- =====================================================================
-- VOZ DO BAIRRO - schema PostgreSQL (APIs Java e .NET no Render)
-- Traducao fiel de banco/script-bd-base.sql (Oracle). Mesmas tabelas, colunas e constraints.
-- Identificadores ENTRE ASPAS e em MAIUSCULAS para as duas APIs usarem os mesmos nomes do contrato.
-- Idempotente: roda a cada subida da API Java (spring.sql.init.mode=always).
-- Datas: TIMESTAMP (sem fuso) sempre em UTC.
-- O Oracle continua sendo a entrega da disciplina de banco (voz-do-bairro-banco).
-- =====================================================================

CREATE TABLE IF NOT EXISTS "VB_BAIRRO" (
  "ID"                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NOME"               VARCHAR(100) NOT NULL,
  "SUBPREFEITURA"      VARCHAR(100) NOT NULL,
  "CIDADE"             VARCHAR(100) DEFAULT 'São Paulo' NOT NULL,
  "META_APOIOS_PADRAO" INTEGER DEFAULT 50 NOT NULL CHECK ("META_APOIOS_PADRAO" > 0),
  CONSTRAINT "UK_VB_BAIRRO_NOME" UNIQUE ("NOME", "CIDADE")
);

CREATE TABLE IF NOT EXISTS "VB_USUARIO" (
  "ID"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NOME"        VARCHAR(120) NOT NULL,
  "EMAIL"       VARCHAR(150) NOT NULL,
  "SENHA_HASH"  VARCHAR(100) NOT NULL,
  "PAPEL"       VARCHAR(20)  DEFAULT 'CIDADAO' NOT NULL,
  "BAIRRO_ID"   BIGINT REFERENCES "VB_BAIRRO"("ID"),
  "DT_CADASTRO" TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  CONSTRAINT "UK_VB_USUARIO_EMAIL" UNIQUE ("EMAIL"),
  CONSTRAINT "CK_VB_USUARIO_PAPEL" CHECK ("PAPEL" IN ('CIDADAO','GESTOR'))
);

CREATE TABLE IF NOT EXISTS "VB_PROPOSTA" (
  "ID"               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "TITULO"           VARCHAR(150)  NOT NULL,
  "DESCRICAO"        VARCHAR(2000) NOT NULL,
  "CATEGORIA"        VARCHAR(30)   NOT NULL,
  "STATUS"           VARCHAR(20)   DEFAULT 'ABERTA' NOT NULL,
  "RESUMO_IA"        VARCHAR(1000),
  "META_APOIOS"      INTEGER       DEFAULT 50 NOT NULL,
  "TOTAL_APOIOS"     INTEGER       DEFAULT 0  NOT NULL,
  "AUTOR_ID"         BIGINT NOT NULL REFERENCES "VB_USUARIO"("ID"),
  "BAIRRO_ID"        BIGINT NOT NULL REFERENCES "VB_BAIRRO"("ID"),
  "DT_CRIACAO"       TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  "DT_VIROU_DEMANDA" TIMESTAMP,
  "PRAZO_RESPOSTA"   TIMESTAMP,
  CONSTRAINT "CK_VB_PROPOSTA_CATEGORIA" CHECK ("CATEGORIA" IN
    ('ZELADORIA','MOBILIDADE','SAUDE','EDUCACAO','LAZER','SEGURANCA','MEIO_AMBIENTE','OUTROS')),
  CONSTRAINT "CK_VB_PROPOSTA_STATUS" CHECK ("STATUS" IN
    ('ABERTA','DEMANDA','ATRASADA','EM_EXECUCAO','CONCLUIDA','RECUSADA')),
  CONSTRAINT "CK_VB_PROPOSTA_APOIOS" CHECK ("TOTAL_APOIOS" >= 0 AND "META_APOIOS" > 0)
);

CREATE TABLE IF NOT EXISTS "VB_RESPOSTA" (
  "ID"             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PROPOSTA_ID"    BIGINT NOT NULL REFERENCES "VB_PROPOSTA"("ID") ON DELETE CASCADE,
  "GESTOR_ID"      BIGINT NOT NULL REFERENCES "VB_USUARIO"("ID"),
  "DECISAO"        VARCHAR(20)   NOT NULL,
  "JUSTIFICATIVA"  VARCHAR(2000) NOT NULL,
  "PRAZO_EXECUCAO" DATE,
  "DT_RESPOSTA"    TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  CONSTRAINT "UK_VB_RESPOSTA_PROPOSTA" UNIQUE ("PROPOSTA_ID"),
  CONSTRAINT "CK_VB_RESPOSTA_DECISAO" CHECK ("DECISAO" IN ('ACEITA','RECUSADA'))
);

CREATE TABLE IF NOT EXISTS "VB_COMENTARIO" (
  "ID"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PROPOSTA_ID" BIGINT NOT NULL REFERENCES "VB_PROPOSTA"("ID") ON DELETE CASCADE,
  "USUARIO_ID"  BIGINT NOT NULL REFERENCES "VB_USUARIO"("ID"),
  "TEXTO"       VARCHAR(1000) NOT NULL,
  "DT_CRIACAO"  TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  "DT_EDICAO"   TIMESTAMP
);

CREATE TABLE IF NOT EXISTS "VB_APOIO" (
  "ID"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "PROPOSTA_ID" BIGINT NOT NULL REFERENCES "VB_PROPOSTA"("ID") ON DELETE CASCADE,
  "USUARIO_ID"  BIGINT NOT NULL REFERENCES "VB_USUARIO"("ID"),
  "DT_APOIO"    TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  CONSTRAINT "UK_VB_APOIO" UNIQUE ("PROPOSTA_ID", "USUARIO_ID")
);

CREATE TABLE IF NOT EXISTS "VB_NOTIFICACAO" (
  "ID"          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "USUARIO_ID"  BIGINT NOT NULL REFERENCES "VB_USUARIO"("ID"),
  "PROPOSTA_ID" BIGINT REFERENCES "VB_PROPOSTA"("ID") ON DELETE CASCADE,
  "MENSAGEM"    VARCHAR(500) NOT NULL,
  "LIDA"        SMALLINT DEFAULT 0 NOT NULL CHECK ("LIDA" IN (0,1)),
  "DT_CRIACAO"  TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL
);

CREATE TABLE IF NOT EXISTS "VB_IDEMPOTENCIA" (
  "CHAVE"           VARCHAR(100) NOT NULL,
  "USUARIO_ID"      BIGINT NOT NULL,
  "ENDPOINT"        VARCHAR(200) NOT NULL,
  "HASH_REQUISICAO" VARCHAR(64)  NOT NULL,
  "STATUS_HTTP"     INTEGER      NOT NULL,
  "CORPO_RESPOSTA"  TEXT,
  "DT_CRIACAO"      TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  CONSTRAINT "PK_VB_IDEMPOTENCIA" PRIMARY KEY ("CHAVE", "USUARIO_ID")
);

CREATE TABLE IF NOT EXISTS "VB_AUDITORIA_APOIO" (
  "ID"              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "OPERACAO"        VARCHAR(10) NOT NULL,
  "APOIO_ID"        BIGINT,
  "PROPOSTA_ID"     BIGINT,
  "USUARIO_ID"      BIGINT,
  "VALORES_ANTIGOS" VARCHAR(4000),
  "VALORES_NOVOS"   VARCHAR(4000),
  "DT_OPERACAO"     TIMESTAMP DEFAULT timezone('UTC', CURRENT_TIMESTAMP) NOT NULL,
  "USUARIO_BD"      VARCHAR(100) DEFAULT CURRENT_USER NOT NULL
);
